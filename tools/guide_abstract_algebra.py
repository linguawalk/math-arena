def verify():
    from math import gcd, lcm, comb
    from itertools import permutations, product
    phi = lambda n: sum(1 for k in range(1, n + 1) if gcd(k, n) == 1)
    ok = []
    ok.append((4 + 5) % 6 == 3 and (3 * 5) % 7 == 1)
    ok.append(12 // gcd(8, 12) == 3 and phi(20) == 8 and sum(1 for d in range(1, 19) if 18 % d == 0) == 6)
    ok.append(lcm(3, 2) == 6)
    s4 = list(permutations(range(4)))
    def order(p):
        k, q = 1, p
        while q != tuple(range(4)):
            q = tuple(p[i] for i in q); k += 1
        return k
    ok.append(sum(1 for p in s4 if order(p) == 2) == 9)
    ok.append(pow(3, 100, 7) == 4)
    ok.append(lcm(4, 6) == 12 and max(lcm(4 // gcd(a, 4), 6 // gcd(b, 6)) for a in range(4) for b in range(6)) == 12)
    ok.append(len({x % 4 for x in range(12)}) == 4 and sum(1 for x in range(12) if x % 4 == 0) == 3)
    ok.append(len({0, 10, 20}) == 30 // 10)
    # 번사이드
    def necklaces(n, c):
        return sum(c ** gcd(k, n) for k in range(n)) // n
    ok.append(necklaces(4, 2) == 6 and necklaces(3, 3) == 11)
    ok.append(sum(1 for a in range(12) if gcd(a, 12) == 1) == 4 and (11 - 4) == 7 and lcm(3, 4) == 12)
    ok.append(sum(1 for d in range(1, 13) if 12 % d == 0) == 6)
    # ℤ3 위 기약 모닉 이차
    irr = [(b, c) for b, c in product(range(3), repeat=2) if all((x * x + b * x + c) % 3 for x in range(3))]
    ok.append(len(irr) == 3)
    ok.append(all((x ** 3 + x + 1) % 2 for x in range(2)) and (1 + 2 + 1) % 5 == 4)
    # 위수 72 아벨군: 분할 수
    part = {1: 1, 2: 2, 3: 3}
    ok.append(part[3] * part[2] == 6)
    # 제2동형정리 예: ℤ24
    H = {x for x in range(24) if x % 6 == 0}; N = {x for x in range(24) if x % 4 == 0}
    HN = {(a + b) % 24 for a in H for b in N}; ok.append(len(HN) // len(N) == 2 and len(H) // len(H & N) == 2)
    assert all(ok), [i for i, t in enumerate(ok) if not t]
    return len(ok)
