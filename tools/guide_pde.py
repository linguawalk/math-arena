def verify():
    import sympy as sp
    x, t, n = sp.symbols("x t n", real=True)
    ok = []
    u = (x - 2 * t) ** 2; ok.append(u.subs({x: 1, t: 3}) == 25 and sp.simplify(u.diff(t) + 2 * u.diff(x)) == 0)
    w = sp.sin(x) * sp.cos(t); ok.append(sp.simplify(w.diff(t, 2) - w.diff(x, 2)) == 0 and w.subs({x: sp.pi / 2, t: sp.pi}) == -1)
    h = sp.exp(-4 * t) * sp.sin(2 * x); ok.append(sp.simplify(h.diff(t) - h.diff(x, 2)) == 0)
    ok.append(sp.integrate(x * sp.sin(x), (x, -sp.pi, sp.pi)) / sp.pi == 2)
    ok.append(sp.integrate(sp.cos(2 * x) * sp.cos(3 * x), (x, -sp.pi, sp.pi)) == 0 and sp.integrate(sp.sin(x) * sp.sin(2 * x), (x, 0, sp.pi)) == 0)
    ok.append(sp.integrate(sp.exp(-x ** 2), (x, -sp.oo, sp.oo)) == sp.sqrt(sp.pi))
    ok.append(sp.integrate(sp.sin(x) ** 2, (x, 0, sp.pi)) / sp.pi == sp.Rational(1, 2))
    y = sp.symbols("y"); ok.append(sp.diff(x ** 2 - y ** 2, x, 2) + sp.diff(x ** 2 - y ** 2, y, 2) == 0)
    assert all(ok), [i for i, v in enumerate(ok) if not v]
    return len(ok)
