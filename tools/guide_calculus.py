def verify():
    import sympy as sp
    x, y, z, t, n, r, th, ph, rho = sp.symbols("x y z t n r theta phi rho", positive=True)
    ok = []
    ok.append(sp.summation(1 / (n * (n + 1)), (n, 1, sp.oo)) == 1 and sp.summation(n / 2 ** n, (n, 1, sp.oo)) == 2)
    ok.append(sp.series(sp.exp(x), x, 0, 4).coeff(x, 3) == sp.Rational(1, 6) and sp.series(sp.log(1 + x), x, 0, 3).coeff(x, 2) == -sp.Rational(1, 2))
    ok.append(sp.integrate(sp.Rational(1, 2) * 4, (th, 0, 2 * sp.pi)) == 4 * sp.pi)
    a, b = sp.Matrix([1, 2, 2]), sp.Matrix([2, 0, 1]); ok.append(list(a.cross(b)) == [2, 3, -4])
    ok.append(sp.Matrix([[1, 0, 0], [0, 2, 0], [1, 1, 3]]).det() == 6)
    f = x ** 2 * y + y ** 3; ok.append(sp.diff(f, x).subs({x: 1, y: 2}) == 4 and sp.diff(f, y).subs({x: 1, y: 2}) == 13)
    g = x ** 2 + 3 * x * y; gr = [sp.diff(g, v).subs({x: 1, y: 1}) for v in (x, y)]
    ok.append(gr == [5, 3] and gr[0] * sp.Rational(3, 5) + gr[1] * sp.Rational(4, 5) == sp.Rational(27, 5))
    h = x ** 2 + y ** 2 - 2 * x - 4 * y; ok.append(h.subs({x: 1, y: 2}) == -5)
    ok.append(sp.integrate(x * y, (x, 0, 1), (y, 0, 2)) == 1 and sp.integrate(r, (r, 0, 3), (th, 0, 2 * sp.pi)) == 9 * sp.pi)
    ok.append(sp.integrate(x + y + z, (x, 0, 1), (y, 0, 1), (z, 0, 1)) == sp.Rational(3, 2))
    ok.append(sp.integrate(rho ** 2 * sp.sin(ph), (rho, 0, 2), (ph, 0, sp.pi), (th, 0, 2 * sp.pi)) == sp.Rational(32, 3) * sp.pi)
    ok.append(sp.integrate(sp.sqrt(9 * sp.sin(t) ** 2 + 9 * sp.cos(t) ** 2 + 16), (t, 0, 2 * sp.pi)) == 10 * sp.pi)
    ok.append(abs(float(sp.sqrt(4.1)) - 2.025) < 0.001)
    assert all(ok), [i for i, v in enumerate(ok) if not v]
    return len(ok)
