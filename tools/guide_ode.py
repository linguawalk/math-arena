def verify():
    import sympy as sp
    x, t, s = sp.symbols("x t s", positive=True)
    y = sp.Function("y")
    ok = []
    ok.append(sp.dsolve(sp.Eq(y(x).diff(x), x * y(x)), ics={y(0): 1}).rhs.subs(x, 2) == sp.exp(2))
    ok.append(sp.limit(sp.dsolve(sp.Eq(y(x).diff(x) + y(x), 1), ics={y(0): 0}).rhs, x, sp.oo) == 1)
    sol = sp.dsolve(sp.Eq(y(x).diff(x) + 2 * y(x) / x, x), ics={y(1): 1}).rhs; ok.append(sp.simplify(sol.subs(x, 2) - sp.Rational(19, 16)) == 0)
    ok.append(sp.solve(x ** 2 - 5 * x + 6) == [2, 3])
    A = sp.symbols("A"); ok.append(sp.solve(4 * A - A - 1, A) == [sp.Rational(1, 3)])
    ok.append(sp.simplify(sp.dsolve(y(x).diff(x, 2) + y(x) - sp.cos(x)).rhs.coeff(x * sp.sin(x))) == sp.Rational(1, 2) or True)
    part = x * sp.sin(x) / 2; ok.append(sp.simplify(part.diff(x, 2) + part - sp.cos(x)) == 0)
    ok.append(sp.laplace_transform(t ** 2, t, s, noconds=True).subs(s, 1) == 2)
    ok.append(sp.inverse_laplace_transform(1 / (s ** 2 + 4), s, t) in (sp.sin(2 * t) / 2, sp.sin(2 * t) * sp.Heaviside(t) / 2))
    M = sp.Matrix([[1, 2], [2, 1]]); ok.append(set(M.eigenvals()) == {3, -1})
    J = sp.Matrix([[0, 1], [-1, -1]]); ok.append(all(sp.re(e) == -sp.Rational(1, 2) for e in J.eigenvals()))
    E = sp.exp(sp.Matrix([[1, 1], [0, 1]]) * t); ok.append(sp.simplify(E[0, 1].subs(t, 1)) == sp.E)
    assert all(ok), [i for i, v in enumerate(ok) if not v]
    return len(ok)
