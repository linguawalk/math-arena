def verify():
    import sympy as sp
    x, n = sp.symbols("x n", positive=True)
    ok = []
    ok.append(sp.limit((2 * n + 1) / (n + 3), n, sp.oo) == 2 and sp.limit((1 + 1 / n) ** n, n, sp.oo) == sp.E)
    ok.append(sp.summation(1 / n ** 2, (n, 1, sp.oo)) == sp.pi ** 2 / 6)
    ok.append(sp.limit((1 - sp.cos(x)) / x ** 2, x, 0) == sp.Rational(1, 2))
    ok.append(sum(sp.Rational(k, 4) for k in range(1, 5)) / 4 == sp.Rational(5, 8) and sum(sp.Rational(k, 4) for k in range(0, 4)) / 4 == sp.Rational(3, 8))
    ok.append(sp.diff(sp.integrate(sp.Symbol("t") ** 3, (sp.Symbol("t"), 1, x)), x).subs(x, 2) == 8)
    ok.append(sp.summation(n * sp.Rational(1, 2) ** (n - 1), (n, 1, sp.oo)) == 4)
    ok.append(sp.integrate(1 / (1 - x), (x, 0, sp.Rational(1, 2))) == sp.log(2))
    ok.append(sp.maximum(x * (1 - x), x, sp.Interval(0, 1)) == sp.Rational(1, 4))
    ok.append((3 ** 2 - 1 ** 2) / (3 - 1) == 2 * 2)
    assert all(ok), [i for i, v in enumerate(ok) if not v]
    return len(ok)
