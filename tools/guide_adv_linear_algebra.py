def verify():
    import numpy as np, sympy as sp
    from math import comb
    ok = []
    x = sp.symbols("x")
    ok.append(sp.integrate(x, (x, 0, 1)) == sp.Rational(1, 2) and sp.integrate(x * x, (x, 0, 1)) == sp.Rational(1, 3))
    ok.append(sp.integrate(x - sp.Rational(1, 2), (x, 0, 1)) == 0)
    A = sp.Matrix([[2, 1], [0, 2]]); ok.append((A - 2 * sp.eye(2)) != sp.zeros(2) and (A - 2 * sp.eye(2)) ** 2 == sp.zeros(2))
    R_ = sp.Matrix([[0, -1], [1, 0]]); ok.append(set(R_.eigenvals()) == {sp.I, -sp.I} and R_ * R_.T == R_.T * R_ and R_ != R_.T)
    B = sp.Matrix([[1, 2 * sp.I], [3, 4]]); ok.append(B.H[0, 1] == 3)
    ok.append(np.allclose(np.linalg.svd(np.array([[0, 2], [0, 0]]), compute_uv=False), [2, 0]))
    C = sp.Matrix([[1, 2], [3, 4]]); ok.append(C ** 2 == 5 * C + 2 * sp.eye(2))
    ok.append(comb(4, 2) == 6)
    # 쌍대기저
    V = sp.Matrix([[1, 1], [0, 1]]); D = V.inv(); ok.append((D.row(0) * sp.Matrix([3, 5]))[0] == -2)
    # D 행렬 (3,4)
    M = sp.zeros(4); basis = [1, x, x ** 2, x ** 3]
    for j, b in enumerate(basis):
        d = sp.Poly(sp.diff(b, x), x); coeffs = [d.coeff_monomial(x ** i) for i in range(4)]
        for i in range(4): M[i, j] = coeffs[i]
    ok.append(M[2, 3] == 3 and M.rank() == 3)
    ok.append(sp.Matrix([[1, 4, 5], [0, 2, 6], [0, 0, 3]]).trace() == 6)
    assert all(ok), [i for i, t in enumerate(ok) if not t]
    return len(ok)
